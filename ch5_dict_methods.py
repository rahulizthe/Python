a ={"rahul": 100,
    "abbas": 100,
    "harry":99}
#methods of dictionary.

#1 print all items in dictionary.
print(a.items())
#2 print all keys in dictionary.
print(a.keys())
#3 print all values in dictionary.
print(a.values())
#4 update key value pairs in dictionary.
a.update({"rahul":99,"aman":99})
print(a)
#5 get the value of key.
print(a.get("rahul"))
